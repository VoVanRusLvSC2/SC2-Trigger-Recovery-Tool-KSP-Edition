function replayIncludes(script, files) {































    const isIncludeStatement = (node) => node.kind === K.IncludeStatement;































    const key = (name) => name.replaceAll('\\', '/').replace(/\.galaxy$/iu, '').toLowerCase();































    const byKey = new Map(files.map(file => [key(file.fileName), file]));































    const reached = new Set();































    const expand = (text) => {































        const parsed = parseGalaxySource(text, 'include-input.galaxy');































        if (parsed.parseDiagnostics.length)































            throw new TypeError('Cannot inline malformed map includes');































        let result = '', cursor = 0;































        for (const node of parsed.statements) {































            if (!isIncludeStatement(node))































                continue;































            const target = node.path?.value ?? node.path?.text?.replace(/^"|"$/gu, '');































            const file = typeof target === 'string' ? byKey.get(key(target)) : undefined;































            if (!file)































                continue;































            result += text.slice(cursor, node.pos);































            if (!reached.has(file)) {































                reached.add(file);































                result += '\n' + expand(file.text) + '\n';































            }































            cursor = node.end;































        }































        return result + text.slice(cursor);































    };































    return expand(script);































}































function replayKnownTransform(stage) {































    if (stage.kind === 'EXISTING_MAP_INCLUDE_INLINING') {































        if (stage.materials.some(file => file.kind !== 'ADDITIONAL_SCRIPT'))































            throw new Error('Unexpected include transform material kind');































        return replayIncludes(stage.parentText, stage.materials);































    }































    if (stage.kind === 'EXISTING_CUSTOM_AI_RECOVERY') {































        if (stage.materials.some(file => file.kind !== 'CUSTOM_AI_SCRIPT' && file.kind !== 'DEPENDENCY_CUSTOM_AI_DOCUMENT'))































            throw new Error('Unexpected Custom AI transform material kind');































        const files = stage.materials.filter(file => file.kind === 'CUSTOM_AI_SCRIPT');































        const documents = stage.materials.filter(file => file.kind === 'DEPENDENCY_CUSTOM_AI_DOCUMENT').sort((a, b) => Number(a.fileName) - Number(b.fileName)).map(file => file.text);































        const recovered = recoverCustomAi(stage.parentText, files, documents);































        if (recovered.state !== 'recovered')































            throw new Error('Known Custom AI transform is not independently proved');































        return recovered.value.script;































    }































    throw new Error('Unknown semantic source transform');































}































/** Called only at the existing service transform boundary. Verify the offered































 * source first, then bind each actual transform result to its immediate input































 * and SHA-verified materials. The semantic script stays an owned source.































 */































export function deriveSemanticInputSnapshot(parent, sourceScript, header, libraryId, stages, hashText) {































    if (!parent)































        return undefined;































    if (!hashText)































        throw new Error('Semantic source derivation requires a content verifier');































    const scriptName = `Lib${libraryId}.galaxy`, headerName = `Lib${libraryId}_h.galaxy`;































    const roots = parent.files.filter(file => file.fileName === scriptName);































    const headers = parent.files.filter(file => file.fileName === headerName);































    if (roots.length !== 1 || headers.length !== 1)































        throw new Error('Semantic source identity is missing or ambiguous');































    const root = roots[0], headerIdentity = headers[0];































    if (root.owned !== true || !root.contentSha256 || hashText(sourceScript) !== root.contentSha256)































        throw new Error('Original owned source SHA failed before semantic transforms: ' + scriptName);































    if (headerIdentity.owned !== true || !headerIdentity.contentSha256 || hashText(header) !== headerIdentity.contentSha256)































        throw new Error('Original owned header SHA failed before semantic transforms: ' + headerName);































    let current = { ...root, text: sourceScript };































    const proofs = [...(parent.semanticStages ?? [])];































    for (const stage of stages) {































        if (hashText(stage.parentText) !== current.contentSha256 || stage.parentText !== current.text)































            throw new Error('Semantic transform is not chained to the verified owned source');































        const materials = stage.materials.map(material => {































            const matches = parent.semanticMaterials?.filter(identity => identity.kind === material.kind && identity.fileName === material.fileName) ?? [];































            if (matches.length !== 1 || hashText(material.text) !== matches[0].contentSha256)































                throw new Error('Semantic transform material SHA failed: ' + material.kind + ':' + material.fileName);































            return { ...matches[0] };































        });































        if (replayKnownTransform(stage) !== stage.derivedText)































            throw new Error('Semantic transform output differs from exact known transform');































        const digest = hashText(stage.derivedText);































        const derivedSourceId = `semantic:${stage.kind}:${current.sourceId}:${digest}`;































        proofs.push({ kind: stage.kind, parentSourceId: current.sourceId, parentContentSha256: current.contentSha256, derivedSourceId, derivedContentSha256: digest, materials });































        current = { ...current, text: stage.derivedText, owned: true, sourceId: derivedSourceId, contentSha256: digest };































    }































    if (stages.length === 0)































        return parent;































    return { ...parent, files: parent.files.map(file => file.fileName === scriptName ? current : file), semanticStages: proofs };































}































