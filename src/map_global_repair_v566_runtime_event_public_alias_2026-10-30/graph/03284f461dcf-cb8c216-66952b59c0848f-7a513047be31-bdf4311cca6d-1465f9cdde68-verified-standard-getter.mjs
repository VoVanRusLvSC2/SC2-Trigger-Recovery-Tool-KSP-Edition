    const alias = call.expression.name, details = inputs.get(session), facts = details?.bindings.filter(b => b.alias === alias);































    if (!details || facts?.length !== 1)































        return false;































    const fact = facts[0], definition = ctx.funcNameToFuncDef.get(fact.alias);































