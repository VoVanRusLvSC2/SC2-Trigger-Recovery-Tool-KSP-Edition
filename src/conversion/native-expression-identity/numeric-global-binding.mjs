// Reuse the established numeric Identifier model, including collision suffixes.































import {resolveVariableGalaxyName as original,namingIndexes} from "./core-alternate.mjs";































import {globalVariables} from "../../sdk/array-values/modules/triggers/services/galaxy-conversion/internal/conversion-model.js";































import {globalVariableNames} from "../../ast/explicit-numeric-global-model.mjs";































export function resolveVariableGalaxyName(variable,ref,ctx){































 const owner=ref?.library??ctx.libId;































 if(owner===ctx.libId&&ctx.localVarIds?.has(variable.id))return original(variable,ref,ctx);































 if(!/^\d[A-Za-z_0-9]*$/u.test(variable.identifier??'')||variable.flags?.includes('NoScriptPrefix'))return original(variable,ref,ctx);































 const library=owner===ctx.libId?ctx.library:ctx.allLibraries?.get(owner);































 if(!library)return original(variable,ref,ctx);































 const globals=globalVariables(library);if(!globals.some(v=>v===variable||v.id===variable.id))return original(variable,ref,ctx);































 const indexes=ctx.globalVariableNamesByLibrary??namingIndexes().globalVariableNamesByLibrary;































 const names=globalVariableNames(owner,globals);indexes.set(library,names);































 return original(variable,ref,{...ctx,globalVariableNamesByLibrary:indexes});































}































